type ReviewedExerciseSeed = Pick<
  Exercise,
  'id' | 'name' | 'englishName' | 'aliases' | 'patternIds' | 'equipment' | 'techniqueLevel'
>

const reviewedExercise = (seed: ReviewedExerciseSeed): Exercise => {
  const displayCategoryId = displayCategoryByExerciseId[seed.id]
  if (!displayCategoryId) throw new Error(`Missing display category for canonical Exercise: ${seed.id}`)
  return {
    ...seed,
    displayCategoryId,
    bodyRegions: [],
    primaryMuscles: [],
    secondaryMuscles: [],
    goals: [],
    coachCues: [],
    commonErrors: [],
    regressions: [],
    progressions: [],
    contraindications: [],
    riskNotes: [],
  }
}

