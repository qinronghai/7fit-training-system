import type {
  AlternativeExercise,
  Count,
  ExercisePrescription,
  ExerciseRole,
  ExerciseKey,
  Laterality,
  NumericRange,
  PrepItem,
  PrepPhase,
  ProgramLevel,
  ProgrammingTemplate,
  ProgrammingTemplateLevel,
  RampUpSet,
  TrainingBlock,
  TrainingExercise,
} from './types'

const COACH_NOTE = '以动作质量为先；教练可按会员当日状态调整负荷，不追加固定泡沫轴。'

const prep = (
  exerciseKey: ExerciseKey,
  displayName: string,
  phase: PrepPhase,
  prescription: ExercisePrescription,
  reason: string,
  laterality?: Laterality,
): PrepItem => ({
  exerciseKey,
  displayName,
  phase,
  prescription,
  reason,
  ...(laterality ? { laterality } : {}),
})

const ramp = (
  exerciseKey: ExerciseKey,
  displayName: string,
  order: number,
  reps: Count,
  loadGuidance: string,
  restSeconds: Count,
  targetRole: 'PRIMARY' | 'SECONDARY' = 'PRIMARY',
  laterality?: Laterality,
): RampUpSet => ({
  exerciseKey,
  displayName,
  order,
  reps,
  loadGuidance,
  restSeconds,
  targetRole,
  ...(laterality ? { laterality } : {}),
})

const alternative = (
  exerciseKey: ExerciseKey,
  displayName: string,
  reason: AlternativeExercise['reason'],
  preserves: AlternativeExercise['preserves'],
  coachNote?: string,
): AlternativeExercise => ({
  exerciseKey,
  displayName,
  reason,
  preserves,
  ...(coachNote ? { coachNote } : {}),
})

const exercise = (value: TrainingExercise): TrainingExercise => value

const strengthBlock = (
  exercises: TrainingExercise[],
  restBetweenSetsSeconds: Count = 120,
): TrainingBlock => ({
  id: 'strength',
  kind: 'strength',
  label: 'Strength Block',
  exercises,
  restBetweenSetsSeconds,
})

const circuitBlock = (
  exercises: TrainingExercise[],
  rounds: Count = { min: 2, max: 3 },
  restBetweenRoundsSeconds: Count = 120,
  transitionSeconds: Count = 60,
): TrainingBlock => ({
  id: 'circuit',
  kind: 'circuit',
  label: '3C Circuit',
  exercises,
  rounds,
  restBetweenRoundsSeconds,
  transitionSeconds,
})

const level = (
  programLevel: ProgramLevel,
  primaryGoal: string,
  prepItems: PrepItem[],
  rampUp: RampUpSet[],
  blocks: TrainingBlock[],
  estimatedMinutes: NumericRange,
  secondaryGoal?: string,
): ProgrammingTemplateLevel => ({
  programLevel,
  primaryGoal,
  ...(secondaryGoal ? { secondaryGoal } : {}),
  prep: prepItems,
  rampUp,
  blocks,
  estimatedMinutes,
  coachNote: COACH_NOTE,
})

const template = (
  id: string,
  code: string,
  name: string,
  description: string,
  levels: Record<ProgramLevel, ProgrammingTemplateLevel>,
): ProgrammingTemplate => ({
  id,
  code,
  system: '3c',
  name,
  description,
  levels,
})

